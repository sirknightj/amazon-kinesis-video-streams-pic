#!/usr/bin/env python3
"""
Generates docs/status-codes.md - a lookup table of every STATUS_* code defined in the public headers,
with the computed hex value that shows up in the logs.

Usage:
    python3 scripts/generate-status-codes.py           # regenerate docs/status-codes.md
    python3 scripts/generate-status-codes.py --check   # exit 1 if docs/status-codes.md is out of date
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, 'docs', 'status-codes.md')
HEADERS = 'src/*/include/com/amazonaws/kinesis/video/*/*.h'

DEFINE = re.compile(r'^\s*#\s*define\s+(STATUS_\w+)\s+(.+?)\s*(?://.*)?$')
TOKEN = re.compile(r'\s*(0[xX][0-9a-fA-F]+|\d+|STATUS_\w+|[()+])')


def parse_headers():
    """Returns [(name, expression, module)] in header order, skipping function-like macros."""
    defines = []
    for path in sorted(glob.glob(os.path.join(ROOT, HEADERS))):
        module = os.path.relpath(path, ROOT).split(os.sep)[1]
        with open(path) as f:
            for line in f:
                m = DEFINE.match(line)
                if m:
                    defines.append((m.group(1), m.group(2), module))
    return defines


def evaluate(name, exprs, cache):
    """Evaluates 'STATUS_X_BASE + 0x0001' style expressions. Returns (value, [referenced names])."""
    if name in cache:
        return cache[name]
    expr = re.sub(r'\(\s*STATUS\s*\)', '', exprs[name])
    pos, py, refs = 0, [], []
    while pos < len(expr):
        m = TOKEN.match(expr, pos)
        if not m:
            raise ValueError(f'{name}: cannot evaluate {exprs[name]!r}')
        tok = m.group(1)
        if tok.startswith('STATUS_'):
            py.append(str(evaluate(tok, exprs, cache)[0]))
            refs.append(tok)
        else:
            py.append(str(int(tok, 0)) if tok[0].isdigit() else tok)
        pos = m.end()
    cache[name] = (eval(' '.join(py), {'__builtins__': {}}), refs)
    return cache[name]


def generate():
    defines = parse_headers()
    exprs = {n: e for n, e, _ in defines}
    modules = {n: mod for n, _, mod in defines}
    cache = {}
    values = {n: evaluate(n, exprs, cache) for n in exprs}
    bases = {r for _, refs in values.values() for r in refs}

    # Group every code under the base it is defined from
    groups = {}
    for name, _, _ in defines:
        if name in bases:
            continue
        refs = values[name][1]
        groups.setdefault(refs[0] if refs else None, []).append(name)

    by_value = {}
    for name, _, _ in defines:
        if name not in bases:
            by_value.setdefault(values[name][0], []).append(name)
    shared = {v: names for v, names in by_value.items() if len(names) > 1}

    hexv = lambda v: f'0x{v:08x}'
    out = [
        '<!-- Generated by scripts/generate-status-codes.py from the public headers. Do not edit by hand. -->',
        '# Status Codes',
        '',
        'Every PIC API returns a `STATUS`. `STATUS_SUCCESS` (0x00000000) means success; any other value is an error.',
        'Search this page for the code printed in your logs, for example `0x5200002e`.',
        '',
        'Codes are grouped by the base they are defined from. The base identifies the module that returned the error.',
        '',
    ]
    if shared:
        out += ['**Note:** some values are shared by more than one name - see [Shared values](#shared-values).', '']
    for base in sorted(groups, key=lambda b: -1 if b is None else values[b][0]):
        title = 'Common' if base is None else f'{base} ({hexv(values[base][0])})'
        mod = modules[groups[base][0]]
        out += [f'## {title}', '', f'Defined in the `{mod}` module.', '', '| Hex | Decimal | Name |', '|---|---|---|']
        for name in groups[base]:
            v = values[name][0]
            out.append(f'| {hexv(v)} | {v} | {name} |')
        out.append('')
    if shared:
        out += ['## Shared values', '', 'These values are defined by more than one name.', '', '| Hex | Names |', '|---|---|']
        for v in sorted(shared):
            out.append(f'| {hexv(v)} | {", ".join(shared[v])} |')
        out.append('')
    return '\n'.join(out), shared


def main():
    content, shared = generate()
    for v, names in sorted(shared.items()):
        print(f'warning: 0x{v:08x} is shared by {", ".join(names)}', file=sys.stderr)
    if '--check' in sys.argv:
        current = open(OUTPUT).read() if os.path.exists(OUTPUT) else ''
        if current != content:
            print(f'{os.path.relpath(OUTPUT, ROOT)} is out of date. Run: python3 scripts/generate-status-codes.py', file=sys.stderr)
            return 1
        return 0
    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, 'w', newline='\n') as f:
        f.write(content)
    return 0


if __name__ == '__main__':
    sys.exit(main())
